#!/usr/bin/env bash
# Produce the common run-count section for a draft experiment report.
# Experiment-specific tables are added before the experiment moves to running.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

id="${1:-}"
[ -n "$id" ] || die 'usage: experiment-report.sh E0001'

runs=$(cat "$ROOT/research/runs"/*.jsonl 2>/dev/null \
    | grep -c "\"experiment\":\"$id\"" || true)

printf '# %s report\n\n' "$id"
printf 'Generated by `scripts/experiment-report.sh %s`.\n\n' "$id"
printf 'Runs recorded: %s\n\n' "${runs:-0}"

if [ "${runs:-0}" -eq 0 ]; then
    printf 'No runs recorded.\n'
    exit 0
fi

printf 'Run records are present. Add experiment-specific tables before setting the manifest status to `reported`.\n'
